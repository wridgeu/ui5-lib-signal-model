/**
 * Renders published benchmark results from their raw data.
 *
 * Reads the merged JSON written by `npm run bench:stable -- --json <file>`
 * and regenerates, deterministically:
 * - `docs/benchmark-results.svg` (chart of the key scenarios)
 * - the generated block in `packages/lib/test/benchmark/README.md`
 *   (run details, full results table, summary)
 *
 * @example
 *   npm run bench:stable -- --runs 10 --json docs/benchmark-results.json
 *   npm run bench:render
 *
 * @see {@link run-benchmark-stable.mjs} Produces the input
 * @see {@link ../packages/lib/test/benchmark/bench-stats.mjs} Result wording
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe } from "../packages/lib/test/benchmark/bench-stats.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dataFile = join(root, "docs/benchmark-results.json");
const svgFile = join(root, "docs/benchmark-results.svg");
const readmeFile = join(root, "packages/lib/test/benchmark/README.md");

/** Scenarios shown in the chart, by their number in the results table. */
const CHART_SCENARIOS = [4, 21, 3, 20, 6, 5];

const START = "<!-- bench:results:start (generated by `npm run bench:render`; do not edit) -->";
const END = "<!-- bench:results:end -->";

const data = JSON.parse(await readFile(dataFile, "utf8"));
const { config, environment, floorMs, scenarios } = data;

/**
 * Format a duration with a unit that keeps three to four significant digits.
 *
 * @param {number} ms Duration in milliseconds
 * @returns {string} e.g. `"1449 ms"`, `"27.35 ms"`, `"0.772 ms"`, `"17.2 µs"`
 */
function fmtTime(ms) {
  if (ms >= 100) return ms.toFixed(0) + " ms";
  if (ms >= 1) return ms.toFixed(2) + " ms";
  if (ms >= 0.1) return ms.toFixed(3) + " ms";
  return (ms * 1000).toFixed(1) + " µs";
}

/** A difference the interval supports and that is at least 10%. */
const isClear = (sc) => sc.verdict !== "unclear" && (sc.ratio >= 1.1 || sc.ratio <= 1 / 1.1);

const count = (verdict) => scenarios.filter((sc) => sc.verdict === verdict).length;
const totals =
  `${count("faster")} faster, ${count("slower")} slower, ` +
  `${count("unclear")} no clear difference`;
const chrome = environment.userAgent.match(/Chrome\/(\d+)/)[1];
const browser = `${environment.userAgent.includes("Headless") ? "headless " : ""}Chrome ${chrome}`;
const bindings = config.bindings.toLocaleString("en-US");

// ── README block ─────────────────────────────────────────────────────

/**
 * Render rows as a Markdown table with padded columns (the layout oxfmt produces).
 *
 * @param {string[][]} rows Header row followed by body rows
 * @returns {string} Markdown table
 */
function table(rows) {
  const widths = rows[0].map((_, col) => Math.max(3, ...rows.map((row) => row[col].length)));
  const line = (cells) => `| ${cells.map((cell, col) => cell.padEnd(widths[col])).join(" | ")} |`;
  return [line(rows[0]), line(widths.map((w) => "-".repeat(w))), ...rows.slice(1).map(line)].join(
    "\n",
  );
}

const rows = [
  [
    "#",
    "Binding Type",
    "Scenario",
    "JSONModel",
    "SignalModel",
    "SignalModel vs JSONModel (95% CI)",
  ],
  ...scenarios.map((sc, i) => [
    String(i + 1),
    sc.category,
    sc.name,
    fmtTime(sc.jsonMedian),
    fmtTime(sc.signalMedian),
    isClear(sc) ? `**${describe(sc)}**` : describe(sc),
  ]),
];

const block = `${START}

**Run:** ${config.runs} runs x ${config.rounds} rounds (${config.rounds / 2} samples per model and run), ${bindings} bindings, measured ${data.timestamp.slice(0, 10)}.
**Environment:** OpenUI5 ${environment.ui5}, ${browser}, Node.js ${environment.node.slice(1)}, ${environment.cpu}, ${environment.memoryGb} GB RAM, ${environment.os}.
**Harness floor:** ${fmtTime(floorMs)} per operation (\`setText\` + render pass, no model), included in every time below.

![SignalModel vs JSONModel Benchmark](../../../../docs/benchmark-results.svg)

<details>
<summary>All ${scenarios.length} scenarios (time per operation: model write to re-rendered DOM)</summary>

${table(rows)}

</details>

${totals}. Times are each model's median across runs; the comparison is the geometric mean of the per-run ratios with its 95% confidence interval. Raw data including all samples: [docs/benchmark-results.json](../../../../docs/benchmark-results.json).

${END}`;

const readme = await readFile(readmeFile, "utf8");
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start < 0 || end < start) {
  throw new Error(`Generated-block markers not found in ${readmeFile}`);
}
await writeFile(readmeFile, readme.slice(0, start) + block + readme.slice(end + END.length));

// ── SVG chart ────────────────────────────────────────────────────────

const WIDTH = 760;
const ROW_HEIGHT = 60;
const ROWS_TOP = 84;
const BAR_WIDTH = 590;
const HEIGHT = ROWS_TOP + CHART_SCENARIOS.length * ROW_HEIGHT + 78;

const esc = (text) => text.replaceAll("&", "&amp;").replaceAll("<", "&lt;");

const chartRows = CHART_SCENARIOS.map((number, row) => {
  const sc = scenarios[number - 1];
  const max = Math.max(sc.jsonMedian, sc.signalMedian);
  const bar = (cls, y, ms) => {
    const width = Math.max(3, Math.round((ms / max) * BAR_WIDTH));
    return `<rect class="${cls}" x="0" y="${y}" width="${width}" height="10" rx="${width < 8 ? 1.5 : 4}" />`;
  };
  const text = describe(sc);
  const badgeWidth = Math.round(text.length * 6.7 + 14);
  const kind = isClear(sc) ? "badge" : "badge-eq";
  return `
  <g transform="translate(32, ${ROWS_TOP + row * ROW_HEIGHT})">
    <text class="label" x="0" y="12">#${number} ${esc(sc.name)}</text>
    <rect class="${kind}-bg" x="${696 - badgeWidth}" y="0" width="${badgeWidth}" height="17" rx="4" />
    <text class="${kind}-txt" x="${696 - badgeWidth / 2}" y="12" text-anchor="middle">${text}</text>
    <rect class="track" x="0" y="21" width="600" height="10" rx="4" />
    ${bar("bar-json", 21, sc.jsonMedian)}
    <text class="val" x="696" y="30" text-anchor="end">${fmtTime(sc.jsonMedian)}</text>
    <rect class="track" x="0" y="35" width="600" height="10" rx="4" />
    ${bar("bar-sig", 35, sc.signalMedian)}
    <text class="val-sig" x="696" y="44" text-anchor="end">${fmtTime(sc.signalMedian)}</text>
  </g>`;
}).join("\n");

const sans = '-apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif';
const mono = "ui-monospace, SFMono-Regular, Menlo, Consolas, monospace";

